/**
 * Websites open in the user's browser can send requests to localhost.
 * - DNS rebinding: a site's domain re-pointed at 127.0.0.1 could read the API.
 *   When bound to localhost, only accept Host headers naming localhost.
 * - CSRF: a site could POST "simple" requests (no CORS preflight). Reject
 *   state-changing requests whose Origin isn't this server.
 */
function allowedRequest(req: IncomingMessage): boolean {
  const host = req.headers.host ?? "";
  const local = HOST === "127.0.0.1" || HOST === "localhost";
  if (local && !/^(localhost|127\.0\.0\.1|\[::1\])(:\d+)?$/i.test(host)) return false;
  const origin = req.headers.origin;
  if (req.method !== "GET" && req.method !== "HEAD" && origin && origin !== "null") {
    try {
      if (new URL(origin).host !== host) return false;
    } catch {
      return false;
    }
  }
  return true;
}

/** MCP over HTTP (stateless): AI assistants connect to http://127.0.0.1:<port>/mcp. */
async function handleMcp(req: IncomingMessage, res: ServerResponse) {
  const mcp = createMcpServer(selfURL);
  const transport = new StreamableHTTPServerTransport({ sessionIdGenerator: undefined });
  res.on("close", () => {
    transport.close();
    mcp.close();
  });
  await mcp.connect(transport);
  const body = req.method === "POST" ? await readJson(req) : undefined;
  await transport.handleRequest(req, res, body);
}

let selfURL = `http://127.0.0.1:${PORT}`;

const server = createServer(async (req, res) => {
  const url = new URL(req.url ?? "/", "http://localhost");
  const q = (k: string) => url.searchParams.get(k) ?? "";
  if (!allowedRequest(req)) {
    res.writeHead(403, { "Content-Type": "text/plain" });
    return res.end("Forbidden");
  }
  try {
    if (url.pathname === "/mcp") return await handleMcp(req, res);
    if (url.pathname === "/api" && req.method === "GET") return json(res, API_INDEX);
    if (url.pathname === "/api/state" && req.method === "GET") return json(res, state());
    if (url.pathname === "/api/sync" && req.method === "POST") {
      await sync(false);
      return json(res, state());
    }
    if (url.pathname === "/api/login" && req.method === "POST") {
      // First run: the UI sends the Pronote address.
      const { url: pronote } = await readJson(req).catch(() => ({}));
      if (pronote && !/^https:\/\/[^/]+\/pronote/i.test(pronote)) return json(res, { error: "Adresse Pronote invalide" }, 400);
      await sync(true, pronote || undefined);
      return json(res, state());
    }
    const done = url.pathname.match(/^\/api\/homework\/([^/]+)\/done$/);
    if (done && req.method === "POST") {
      const { done: value } = await readJson(req);
      const result = await setHomeworkDone(decodeURIComponent(done[1]), Boolean(value));
      return json(res, { ...result, ...state() });
    }
    if (url.pathname === "/api/layout" && req.method === "PUT") {
      const layout = await readJson(req);
      if (!Array.isArray(layout?.widgets) || layout.widgets.length > 50) return json(res, { error: "Invalid layout" }, 400);
      store.setSetting("layout", layout);
      return json(res, { ok: true });
    }
    if (url.pathname === "/api/subject-settings" && req.method === "PUT") {
      const value = await readJson(req);
      if (!value || typeof value !== "object" || Array.isArray(value)) return json(res, { error: "Invalid settings" }, 400);
      store.setSetting("subjectSettings", value);
      return json(res, { ok: true });
    }

    // Attachment from homework, lessons, news: its URL from the last sync, or a fresh one.
    if (url.pathname === "/api/file" && req.method === "GET") {
      return serveCached(res, `att:${q("id")}:${q("n")}`, q("n") || "fichier", async () =>
        q("id") ? live.use(async (session) => attachmentURL(session, q("id"), q("n"))) : q("u"));
    }
    // Casier document.
    if (url.pathname === "/api/doc/casier" && req.method === "GET") {
      return serveCached(res, `casier:${q("id")}`, q("n") || "document", () =>
        live.use(async (session) => attachmentURL(session, q("id"), q("n"))));
    }
    // Report card (bulletin) PDF, generated by Pronote on demand.
    if (url.pathname === "/api/doc/bulletin" && req.method === "GET") {
      return serveCached(res, `bia:${q("ident")}`, q("n") || "bulletin.pdf", () =>
        live.use(async (session) => {
          const data = await rawRequest(session, "GenerationPDF", {
            avecDepot: true,
            genreGenerationPDF: 12, // BulletinBIA
            nomFichier: q("n"),
            ident: q("ident"),
            libellePeriodeNotation: q("period"),
            libelleAnnee: q("year"),
          }, 103);
          const path = data?.url?.V ?? data?.url;
          return path ? `${session.information.url}/${encodeURI(path)}` : null;
        }));
    }
    // Homework for any date range (infinite scroll), fetched live and archived.
    if (url.pathname === "/api/homework/range" && req.method === "GET") {
      const from = new Date(`${q("from")}T00:00:00`);
      const to = new Date(`${q("to")}T23:59:59`);
      if (Number.isNaN(+from) || Number.isNaN(+to) || to < from || +to - +from > 120 * 864e5) return json(res, { error: "Invalid range" }, 400);
      const archived = Object.values(store.get<Record<string, any>>("homeworkArchive") ?? {})
        .filter((a: any) => new Date(a.deadline) >= from && new Date(a.deadline) <= to);
      try {
        const items = await live.use((session) => pronote.assignmentsFromIntervals(session, from, to));
        archiveHomework(store, items);
        return json(res, { items: JSON.parse(JSON.stringify(items)), offline: false });
      } catch {
        return json(res, { items: archived, offline: true });
      }
    }
    // Mark an information as read/unread in Pronote. Ids change every session:
    // find the item's current id in a fresh list first.
    if (url.pathname === "/api/news/read" && req.method === "POST") {
      const { key, read } = await readJson(req);
      try {
        await live.use(async (session) => {
          const raw = await rawRequest(session, "PageActualites", { genreRequeteActualite: 0, modesAffActus: { _T: 26, V: "[0]" } }, pronote.TabLocation.News);
          const modes = raw.listeModesAff?.V ?? raw.listeModesAff ?? [];
          const items = modes[0]?.listeActualites?.V ?? [];
          const dateOf = (v: any) => {
            const m = /^(\d{2})\/(\d{2})\/(\d{4})/.exec(v?.V ?? "");
            return m ? new Date(+m[3], +m[2] - 1, +m[1]) : null;
          };
          const it = items.find((i: any) => newsKey(i.L, dateOf(i.dateCreation)) === key);
          if (!it) throw new Error("Information introuvable");
          await rawRequest(session, "SaisieActualites", {
            listeActualites: [{
              N: it.N, L: it.L, E: 2, genrePublic: it.genrePublic, public: it.public?.V ?? it.public, estPublic: it.estPublic ?? true,
              validationDirecte: true, listeQuestions: [],
              marqueLueSeulement: true, lue: Boolean(read), supprimee: false, saisieActualite: false,
            }],
            saisieActualite: false,
            genreSaisie: 0, // tgsa_SaisieActualite
          }, pronote.TabLocation.News);
        });
        store.patch<any>("news", (n) => ({ ...n, items: n.items.map((i: any) => (i.key === key ? { ...i, read: Boolean(read) } : i)) }));
        return json(res, { ok: true, ...state() });
      } catch (err) {
        return json(res, { ok: false, error: err instanceof Error ? err.message : String(err) }, 502);
      }
    }
    // Everyone you can message in Pronote (teachers, staff...), as JSON or CSV.
    if (url.pathname.startsWith("/api/contacts") && req.method === "GET") {
      try {
        const contacts = await live.use(async (session) => {
          const out: any[] = [];
          const kinds: Array<[number, string]> = [[3, "Professeur"], [34, "Personnel"], [4, "Élève"], [5, "Responsable"]];
          for (const [kind, label] of kinds) {
            let raw: any;
            try {
              raw = await rawRequest(session, "ListeRessourcesPourCommunication", {
                filtreElement: { G: session.userResource.kind, L: session.userResource.name, N: session.userResource.id },
                onglet: { N: 0, G: kind },
              }, pronote.TabLocation.Discussions);
            } catch {
              continue; // not allowed for this account
            }
            for (const r of raw?.listeRessourcesPourCommunication?.V ?? []) {
              const subjects = (r.listeRessources?.V ?? []).filter((x: any) => !x.estUneSousMatiere).map((x: any) => x.L);
              const mails = Object.entries(r).filter(([k, v]) => /mail/i.test(k) && typeof v === "string" && v).map(([, v]) => v);
              out.push({
                type: label,
                name: r.L,
                function: r.fonction?.V?.L ?? "",
                subjects: subjects.join(", "),
                principal: Boolean(r.estPrincipal),
                canMessage: Boolean(r.avecDiscussion),
                email: mails.join(", "),
              });
            }
          }
          return out;
        });
        store.put("contacts", contacts);
        if (url.pathname.endsWith(".csv")) {
          const esc = (v: unknown) => `"${String(v ?? "").replace(/"/g, '""')}"`;
          const head = ["Type", "Nom", "Fonction", "Matières", "Professeur principal", "Messagerie Pronote", "E-mail"];
          const rows = contacts.map((c) => [c.type, c.name, c.function, c.subjects, c.principal ? "oui" : "", c.canMessage ? "oui" : "non", c.email].map(esc).join(";"));
          res.writeHead(200, {
            "Content-Type": "text/csv; charset=utf-8",
            "Content-Disposition": `attachment; filename="contacts-etablissement-${new Date().toISOString().slice(0, 10)}.csv"`,
          });
          return res.end("\ufeff" + [head.map(esc).join(";"), ...rows].join("\r\n"));
        }
        return json(res, contacts);
      } catch (err) {
        const cached = store.get<any[]>("contacts");
        if (cached && !url.pathname.endsWith(".csv")) return json(res, cached);
        return json(res, { error: err instanceof Error ? err.message : String(err) }, 502);
      }
    }
    if (url.pathname === "/api/export" && req.method === "GET") {
      res.setHeader("Content-Disposition", `attachment; filename="pronote-export-${new Date().toISOString().slice(0, 10)}.json"`);
      return json(res, { exportedAt: new Date().toISOString(), layout: store.getSetting("layout"), subjectSettings: store.getSetting("subjectSettings"), ...store.all() });
    }

    if (req.method !== "GET") return json(res, { error: "Not found" }, 404);

    // Static files from web/, never outside it. Unknown paths get the app (client routing).
    let file = normalize(join(WEB_DIR, url.pathname === "/" ? "index.html" : url.pathname));
    if (!file.startsWith(WEB_DIR)) return json(res, { error: "Not found" }, 404);
    let body = await readFile(file).catch(() => null);
    if (!body && !extname(file)) {
      file = join(WEB_DIR, "index.html");
      body = await readFile(file);
    }
    if (!body) return json(res, { error: "Not found" }, 404);
    res.writeHead(200, { "Content-Type": MIME[extname(file)] ?? "application/octet-stream", "Cache-Control": "no-cache" });
    res.end(body);
  } catch (err) {
    json(res, { error: String(err) }, 500);
  }
});

