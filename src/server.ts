/** Classifies a failure so the UI can say "offline" or "log in again". */
function classify(err: unknown): SyncStatus {
  const message = err instanceof Error ? `${err.name}: ${err.message}` : String(err);
  const offline = /ERR_INTERNET_DISCONNECTED|ERR_NAME_NOT_RESOLVED|ENOTFOUND|ECONNREFUSED|ETIMEDOUT|ECONNRESET|fetch failed|ERR_NETWORK/i;
  if (err instanceof InteractiveLoginRequired) return { at: Date.now(), ok: false, errorKind: "login", message };
  if (offline.test(message)) return { at: Date.now(), ok: false, errorKind: "offline", message };
  return { at: Date.now(), ok: false, errorKind: "error", message };
}

function sync(interactive = false, url?: string): Promise<SyncStatus> {
  syncing ??= (async () => {
    let status: SyncStatus;
    try {
      const failures = await live.use((session) => syncAll(session, store), { interactive, url });
      // Optional kinds (documents, report cards...) may legitimately fail; keep
      // their errors for the UI without turning the whole sync red.
      store.put("syncWarnings", failures);
      const failed = Object.keys(failures).filter((k) => CORE_KINDS.includes(k));
      status = failed.length
        ? { at: Date.now(), ok: false, errorKind: "error", message: failed.map((k) => `${k}: ${failures[k]}`).join("\n") }
        : { at: Date.now(), ok: true };
    } catch (err) {
      status = classify(err);
    }
    store.logSync(status);
    pronoteURL = (await loadConfig())?.url ?? pronoteURL;
    console.log(`[sync] ${new Date(status.at).toLocaleTimeString("fr-FR")} ${status.ok ? "ok" : `${status.errorKind}: ${status.message}`}`);
    return status;
  })().finally(() => (syncing = null));
  return syncing;
}

/** Ticks homework: instantly when online, queued for the next sync otherwise. */
async function setHomeworkDone(id: string, done: boolean): Promise<{ queued: boolean }> {
  store.patch<any[]>("homework", (list) => list.map((a) => (a.id === id ? { ...a, done } : a)));
  store.patch<Record<string, any>>("homeworkArchive", (m) => {
    const k = Object.keys(m).find((key) => m[key].id === id);
    return k ? { ...m, [k]: { ...m[k], done } } : m;
  });
  try {
    if (!live.isOpen && store.lastSync()?.ok === false) throw new Error("offline");
    await live.use(async (session) => {
      // Ids from an older session are stale: find the homework's current id.
      let current = id;
      const inSnapshot = (store.get<any[]>("homework") ?? []).some((a) => a.id === id);
      const archived = Object.values(store.get<Record<string, any>>("homeworkArchive") ?? {}).find((a) => a.id === id);
      if (!inSnapshot && archived) {
        const day = new Date(archived.deadline);
        const from = new Date(day.getFullYear(), day.getMonth(), day.getDate());
        const fresh = await pronote.assignmentsFromIntervals(session, from, new Date(+from + 864e5 - 1));
        current = fresh.find((a) => homeworkKey(a) === homeworkKey(archived))?.id ?? id;
      }
      await pronote.assignmentStatus(session, current, done);
    });
    return { queued: false };
  } catch {
    store.addPending("homeworkDone", { id, done });
    applyPendingToSnapshot(store);
    return { queued: true };
  }
}

/** Serves a cached file, or fetches it from a fresh Pronote URL and caches it. */
async function serveCached(res: ServerResponse, key: string, name: string, produce: () => Promise<string | null>) {
  const send = ({ body, type }: CachedFile) => {
    res.writeHead(200, {
      "Content-Type": type,
      "Content-Disposition": `inline; filename*=UTF-8''${encodeURIComponent(name)}`,
      "Cache-Control": "private, max-age=86400",
    });
    res.end(body);
  };
  const cached = await readCached(key);
  if (cached) return send(cached);
  try {
    const url = await produce();
    const fresh = url ? await cacheFromURL(key, url) : null;
    if (fresh) return send(fresh);
  } catch (err) {
    console.error(`[file] ${name}: ${err instanceof Error ? err.message : err}`);
  }
  res.writeHead(404, { "Content-Type": "text/html; charset=utf-8" });
  res.end(`<meta charset="utf-8"><p style="font-family:system-ui">Fichier indisponible : Pronote est injoignable et ce fichier n'a pas encore été enregistré. Réessayez une fois connecté.</p>`);
}


const MIME: Record<string, string> = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".svg": "image/svg+xml",
};

const json = (res: ServerResponse, body: unknown, status = 200) => {
  res.writeHead(status, { "Content-Type": "application/json; charset=utf-8", "Cache-Control": "no-store" });
  res.end(JSON.stringify(body));
};

async function readJson(req: IncomingMessage): Promise<any> {
  let body = "";
  for await (const chunk of req) body += chunk;
  return body ? JSON.parse(body) : {};
}

