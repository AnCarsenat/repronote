import { applyPendingToSnapshot, syncAll } from "./store/sync.ts";

const PORT = Number(process.env.PORT ?? 4173);
// Localhost only by default: the data is personal. HOST=0.0.0.0 exposes it on your network.
const HOST = process.env.HOST ?? "127.0.0.1";

/** Self-description of the HTTP API (GET /api). Keep in sync with the routes below. */
const API_INDEX = {
  name: "repronote",
  docs: "https://github.com/AnCarsenat/repronote#api",
  endpoints: [
    { method: "GET", path: "/api", description: "This list." },
    { method: "GET", path: "/api/state", description: "Everything: sync status, layout, subject settings and every data snapshot (homework, timetable, grades, news, notebook, documents, resources, account...)." },
    { method: "POST", path: "/api/sync", description: "Sync now with the saved ENT session (no window). Returns /api/state." },
    { method: "POST", path: "/api/login", description: "Open the login window on this computer, then sync. Returns /api/state." },
    { method: "POST", path: "/api/homework/:id/done", body: "{ done: boolean }", description: "Tick/untick homework (queued if offline)." },
    { method: "PUT", path: "/api/layout", body: "{ widgets: [{ id, type, col, size?, settings? }] }", description: "Home screen layout." },
    { method: "PUT", path: "/api/subject-settings", body: "{ [subject]: { coef, mode: 'normal'|'bonus'|'excluded' } }", description: "Subject coefficients for the computed average." },
    { method: "GET", path: "/api/file?id=&n=&u=", description: "A Pronote attachment (cached locally)." },
    { method: "GET", path: "/api/doc/casier?id=&n=", description: "A document from the casier (cached locally)." },
    { method: "GET", path: "/api/doc/bulletin?ident=&n=&period=&year=", description: "A report card PDF (generated by Pronote, cached locally)." },
    { method: "GET", path: "/api/export", description: "All data as one JSON file." },
  ],
};
const SYNC_EVERY_MS = 30 * 60_000;
const WEB_DIR = fileURLToPath(new URL("../web/", import.meta.url));

const CORE_KINDS = ["user", "homework", "timetable", "grades", "pending"];

const store = new Store();
// News texts already stored don't need to be fetched again at login.
setKnownNews((store.get<any>("news")?.items ?? []).filter((i: any) => i.questions).map((i: any) => i.key));
const live = new LiveSession();
let syncing: Promise<SyncStatus> | null = null;

/** Classifies a failure so the UI can say "offline" or "log in again". */
function classify(err: unknown): SyncStatus {
  const message = err instanceof Error ? `${err.name}: ${err.message}` : String(err);
  const offline = /ERR_INTERNET_DISCONNECTED|ERR_NAME_NOT_RESOLVED|ENOTFOUND|ECONNREFUSED|ETIMEDOUT|ECONNRESET|fetch failed|ERR_NETWORK/i;
  if (err instanceof InteractiveLoginRequired) return { at: Date.now(), ok: false, errorKind: "login", message };
  if (offline.test(message)) return { at: Date.now(), ok: false, errorKind: "offline", message };
  return { at: Date.now(), ok: false, errorKind: "error", message };
}

function sync(interactive = false): Promise<SyncStatus> {
  syncing ??= (async () => {
    let status: SyncStatus;
    try {
      const failures = await live.use((session) => syncAll(session, store), { interactive });
      // Optional kinds (documents, report cards...) may legitimately fail; keep
      // their errors for the UI without turning the whole sync red.
      store.put("syncWarnings", failures);
      const failed = Object.keys(failures).filter((k) => CORE_KINDS.includes(k));
      status = failed.length
        ? { at: Date.now(), ok: false, errorKind: "error", message: failed.map((k) => `${k}: ${failures[k]}`).join("\n") }
        : { at: Date.now(), ok: true };
    } catch (err) {
      status = classify(err);
    }
    store.logSync(status);
    console.log(`[sync] ${new Date(status.at).toLocaleTimeString("fr-FR")} ${status.ok ? "ok" : `${status.errorKind}: ${status.message}`}`);
    return status;
  })().finally(() => (syncing = null));
  return syncing;
}

/** Ticks homework: instantly when online, queued for the next sync otherwise. */
async function setHomeworkDone(id: string, done: boolean): Promise<{ queued: boolean }> {
  store.patch<any[]>("homework", (list) => list.map((a) => (a.id === id ? { ...a, done } : a)));
  try {
    if (!live.isOpen && store.lastSync()?.ok === false) throw new Error("offline");
    await live.use((session) => pronote.assignmentStatus(session, id, done));
    return { queued: false };
  } catch {
    store.addPending("homeworkDone", { id, done });
    applyPendingToSnapshot(store);
    return { queued: true };
  }
}

/** Serves a cached file, or fetches it from a fresh Pronote URL and caches it. */
async function serveCached(res: ServerResponse, key: string, name: string, produce: () => Promise<string | null>) {
  const send = ({ body, type }: CachedFile) => {
    res.writeHead(200, {
      "Content-Type": type,
      "Content-Disposition": `inline; filename*=UTF-8''${encodeURIComponent(name)}`,
      "Cache-Control": "private, max-age=86400",
    });
    res.end(body);
  };
  const cached = await readCached(key);
  if (cached) return send(cached);
  try {
    const url = await produce();
    const fresh = url ? await cacheFromURL(key, url) : null;
    if (fresh) return send(fresh);
  } catch (err) {
    console.error(`[file] ${name}: ${err instanceof Error ? err.message : err}`);
  }
  res.writeHead(404, { "Content-Type": "text/html; charset=utf-8" });
  res.end(`<meta charset="utf-8"><p style="font-family:system-ui">Fichier indisponible : Pronote est injoignable et ce fichier n'a pas encore été enregistré. Réessayez une fois connecté.</p>`);
}


const MIME: Record<string, string> = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".svg": "image/svg+xml",
};

const json = (res: ServerResponse, body: unknown, status = 200) => {
  res.writeHead(status, { "Content-Type": "application/json; charset=utf-8", "Cache-Control": "no-store" });
  res.end(JSON.stringify(body));
};

async function readJson(req: IncomingMessage): Promise<any> {
  let body = "";
  for await (const chunk of req) body += chunk;
  return body ? JSON.parse(body) : {};
}

const state = () => ({
  syncing: syncing !== null,
  connected: live.isOpen,
  lastSync: store.lastSync(),
  lastSuccessfulSync: store.lastSuccessfulSync(),
  pending: store.pending().length,
  layout: store.getSetting("layout"),
  subjectSettings: store.getSetting("subjectSettings"),
  data: store.all(),
});

const server = createServer(async (req, res) => {
  const url = new URL(req.url ?? "/", "http://localhost");
  try {
    if (url.pathname === "/api" && req.method === "GET") return json(res, API_INDEX);
    if (url.pathname === "/api/state" && req.method === "GET") return json(res, state());
    if (url.pathname === "/api/sync" && req.method === "POST") {
      await sync(false);
      return json(res, state());
    }
    if (url.pathname === "/api/login" && req.method === "POST") {
      await sync(true);
      return json(res, state());
    }
    const done = url.pathname.match(/^\/api\/homework\/([^/]+)\/done$/);
    if (done && req.method === "POST") {
      const { done: value } = await readJson(req);
      const result = await setHomeworkDone(decodeURIComponent(done[1]), Boolean(value));
      return json(res, { ...result, ...state() });
    }
    if (url.pathname === "/api/layout" && req.method === "PUT") {
      const layout = await readJson(req);
      if (!Array.isArray(layout?.widgets) || layout.widgets.length > 50) return json(res, { error: "Invalid layout" }, 400);
      store.setSetting("layout", layout);
      return json(res, { ok: true });
    }
    if (url.pathname === "/api/subject-settings" && req.method === "PUT") {
      const value = await readJson(req);
      if (!value || typeof value !== "object" || Array.isArray(value)) return json(res, { error: "Invalid settings" }, 400);
      store.setSetting("subjectSettings", value);
      return json(res, { ok: true });
    }
    const q = (k: string) => url.searchParams.get(k) ?? "";
    // Attachment from homework, lessons, news: its URL from the last sync, or a fresh one.
    if (url.pathname === "/api/file" && req.method === "GET") {
      return serveCached(res, `att:${q("id")}:${q("n")}`, q("n") || "fichier", async () =>
        q("id") ? live.use(async (session) => attachmentURL(session, q("id"), q("n"))) : q("u"));
    }
    // Casier document.
    if (url.pathname === "/api/doc/casier" && req.method === "GET") {
      return serveCached(res, `casier:${q("id")}`, q("n") || "document", () =>
        live.use(async (session) => attachmentURL(session, q("id"), q("n"))));
    }
    // Report card (bulletin) PDF, generated by Pronote on demand.
    if (url.pathname === "/api/doc/bulletin" && req.method === "GET") {
      return serveCached(res, `bia:${q("ident")}`, q("n") || "bulletin.pdf", () =>
        live.use(async (session) => {
          const data = await rawRequest(session, "GenerationPDF", {
            avecDepot: true,
            genreGenerationPDF: 12, // BulletinBIA
            nomFichier: q("n"),
            ident: q("ident"),
            libellePeriodeNotation: q("period"),
            libelleAnnee: q("year"),
          }, 103);
          const path = data?.url?.V ?? data?.url;
          return path ? `${session.information.url}/${encodeURI(path)}` : null;
        }));
    }
    if (url.pathname === "/api/export" && req.method === "GET") {
      res.setHeader("Content-Disposition", `attachment; filename="pronote-export-${new Date().toISOString().slice(0, 10)}.json"`);
      return json(res, { exportedAt: new Date().toISOString(), layout: store.getSetting("layout"), subjectSettings: store.getSetting("subjectSettings"), ...store.all() });
    }

    if (req.method !== "GET") return json(res, { error: "Not found" }, 404);

    // Static files from web/, never outside it. Unknown paths get the app (client routing).
    let file = normalize(join(WEB_DIR, url.pathname === "/" ? "index.html" : url.pathname));
    if (!file.startsWith(WEB_DIR)) return json(res, { error: "Not found" }, 404);
    let body = await readFile(file).catch(() => null);
    if (!body && !extname(file)) {
      file = join(WEB_DIR, "index.html");
      body = await readFile(file);
    }
    if (!body) return json(res, { error: "Not found" }, 404);
    res.writeHead(200, { "Content-Type": MIME[extname(file)] ?? "application/octet-stream", "Cache-Control": "no-cache" });
    res.end(body);
  } catch (err) {
    json(res, { error: String(err) }, 500);
  }
});

// Localhost only: the data is personal.
server.listen(PORT, HOST, () => {
  if (HOST !== "127.0.0.1" && HOST !== "localhost") {
    console.warn(`⚠ Listening on ${HOST}: anyone on your network can read your Pronote data and act as you.`);
  }
  console.log(`Pronote UI: http://localhost:${PORT}`);
  sync();
  setInterval(() => sync(), SYNC_EVERY_MS);
});

// Log out of Pronote on Ctrl+C so the next start isn't refused.
for (const signal of ["SIGINT", "SIGTERM"] as const) {
  process.on(signal, async () => {
    await live.reset();
    process.exit(0);
  });
}
